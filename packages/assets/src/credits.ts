// Licence / attribution registry. Every downloaded (not generated) asset gets an entry in assets.credits.json:
// what it is, who made it, where it came from, under which licence, and whether we changed it. validateCredits()
// checks entries against the licence table (attribution-required licences need an author and source, share-alike
// ones need the modified flag, unknown or "not for redistribution" licences are flagged) and that the files exist
// and every file under the asset roots is covered. formatAttribution() renders the credits text for an about screen.
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, resolve } from "node:path";

export interface CreditEntry {
  /** File path or glob ("*" within a segment, "**" across) relative to the credits file. */
  path: string;
  title: string;
  author?: string;
  /** Where it was downloaded (page URL). */
  source?: string;
  /** SPDX-ish id: CC0-1.0, CC-BY-4.0, CC-BY-SA-4.0, OFL-1.1, MIT, "generated", "own", "paid"... */
  licence: string;
  /** Changed from the original (required to be stated for share-alike / BY licences). */
  modified?: boolean | string;
  notes?: string;
}

export interface CreditsFile {
  /** Folders whose every file must be covered by an entry (relative to the credits file). */
  roots?: string[];
  /** Globs under the roots that need no entry (generated outputs, raw sheets...). */
  ignore?: string[];
  entries: CreditEntry[];
}

export interface LicenceInfo {
  name: string;
  attribution: boolean;
  shareAlike: boolean;
  /** Must not be shipped in a public build / repository. */
  private?: boolean;
  nonCommercial?: boolean;
  url?: string;
}

