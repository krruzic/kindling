export interface CreditIssue {
  level: "error" | "warning";
  path: string;
  message: string;
}

export function loadCredits(file: string): CreditsFile {
  return JSON.parse(readFileSync(file, "utf8")) as CreditsFile;
}

/** Glob to RegExp: "**" spans directories, "*" and "?" stay within one segment. */
export function globToRegExp(glob: string): RegExp {
  let re = "";
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === "*" && glob[i + 1] === "*") {
      re += glob[i + 2] === "/" ? "(?:.*/)?" : ".*";
      i += glob[i + 2] === "/" ? 2 : 1;
    } else if (c === "*") re += "[^/]*";
    else if (c === "?") re += "[^/]";
    else re += c.replace(/[.+^${}()|[\]\\]/g, "\\$&");
  }
  return new RegExp(`^${re}$`);
}

function walk(dir: string, out: string[] = []): string[] {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** Validates a credits file; `base` is the directory paths are relative to. */
export function validateCredits(c: CreditsFile, base: string, opts: { publicBuild?: boolean } = {}): CreditIssue[] {
  const issues: CreditIssue[] = [];
  const err = (path: string, message: string) => issues.push({ level: "error", path, message });
  const warn = (path: string, message: string) => issues.push({ level: "warning", path, message });
  if (!Array.isArray(c.entries)) return [{ level: "error", path: "", message: "entries must be an array" }];
  const roots = (c.roots ?? []).map((r) => resolve(base, r));
  const files = roots.flatMap((r) => walk(r)).map((f) => relative(base, f).split("\\").join("/"));
  const seen = new Set<string>();
  for (const e of c.entries) {
    const p = e.path ?? "?";
    if (!e.path) err(p, "missing path");
    if (seen.has(p)) err(p, "duplicate entry");
    seen.add(p);
    if (!e.title) err(p, "missing title");
    const lic = LICENCES[e.licence];
    if (!e.licence) err(p, "missing licence");
    else if (!lic) err(p, `unknown licence "${e.licence}" (add it to LICENCES or use an SPDX id)`);
    else {
      if (lic.attribution && !e.author) err(p, `${lic.name} requires an author for attribution`);
      if (lic.attribution && !e.source && e.licence.startsWith("CC")) err(p, `${lic.name} requires a source link`);
      if (lic.shareAlike && e.modified === undefined) err(p, `${lic.name}: say whether it was modified`);
      if (lic.private && opts.publicBuild) err(p, `${lic.name}: must not ship in a public build`);
      if (lic.nonCommercial) warn(p, `${lic.name}: non-commercial only`);
    }
    if (e.path) {
      const re = globToRegExp(e.path);
      const hasGlob = /[*?]/.test(e.path);
      if (hasGlob ? !files.some((f) => re.test(f)) : !existsSync(resolve(base, e.path))) warn(p, "matches no file");
    }
  }
  const covered = c.entries.filter((e) => e.path).map((e) => globToRegExp(e.path));
  const ignored = (c.ignore ?? []).map(globToRegExp);
  for (const f of files)
    if (!covered.some((re) => re.test(f)) && !ignored.some((re) => re.test(f))) err(f, "file has no credits entry");
  return issues;
}

/** Credits text (markdown) for everything that needs attribution, grouped by licence. */
export function formatAttribution(c: CreditsFile): string {
  const groups = new Map<string, CreditEntry[]>();
  for (const e of c.entries) {
    if (!LICENCES[e.licence]?.attribution) continue;
    let g = groups.get(e.licence);
    if (!g) groups.set(e.licence, (g = []));
    g.push(e);
  }
  const out: string[] = [];
  for (const [id, list] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const lic = LICENCES[id];
    out.push(`## ${lic.name}${lic.url ? ` (${lic.url})` : ""}`, "");
    for (const e of list.sort((a, b) => a.title.localeCompare(b.title))) {
      const mod = e.modified ? ` (modified${typeof e.modified === "string" ? `: ${e.modified}` : ""})` : "";
      out.push(`- "${e.title}" by ${e.author}${e.source ? ` (${e.source})` : ""}${mod}`);
    }
    out.push("");
  }
  return out.join("\n");
}
