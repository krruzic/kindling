// Launcher script generator for sharded headless runs. The generated bash script:
//   ./run.sh          starts a detached coordinator (setsid nohup, survives the terminal / agent session) that runs
//                     SHARDS copies of the command with SHARD=i SHARDS=n (+ your env), stdout -> OUT/shard-i.jsonl,
//                     stderr -> OUT/shard-i.log, waits for all, then writes OUT/DONE (exit code per shard) atomically
//   ./run.sh wait     ONE blocking wait for the coordinator (tail --pid; no sleep-polling loop), then prints DONE
//   ./run.sh status   rows written so far per shard
// Grudge's full balance suites ran this way on 16 cores for ~2.5 h; focused A/B runs ~12 min.
import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

export interface LauncherOptions {
  /** Shell command each shard runs, e.g. "node --experimental-transform-types --no-warnings tools/sim.ts". */
  command: string;
  shards: number;
  /** Output directory for shard files and DONE (resolved to absolute). */
  outDir: string;
  /** Working directory for the shards (default: the current directory, absolute). */
  cwd?: string;
  /** Extra env for every shard (GAMES, FOCUS, MUT...). Values are shell-quoted. */
  env?: Record<string, string | number>;
  /** nice level for the shards (default 10, keeps the desktop responsive). */
  nice?: number;
  /** Title for the header comment. */
  name?: string;
}

/** Single-quote for bash. */
export function shq(v: string | number): string {
  return `'${String(v).replace(/'/g, `'\\''`)}'`;
}

export function launcherScript(opts: LauncherOptions): string {
  if (!(opts.shards >= 1) || !Number.isInteger(opts.shards)) throw new Error(`launcher: bad shards ${opts.shards}`);
  for (const k of Object.keys(opts.env ?? {}))
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) throw new Error(`launcher: bad env name ${k}`);
  const out = resolve(opts.outDir);
  const cwd = resolve(opts.cwd ?? ".");
  const env = Object.entries(opts.env ?? {})
    .map(([k, v]) => `${k}=${shq(v)}`)
    .join(" ");
  const nice = opts.nice ?? 10;
  return `#!/usr/bin/env bash
# ${opts.name ?? "headless run"} (generated by @kindling/core launcherScript)
#   $0          start ${opts.shards} shards detached
#   $0 wait     block until every shard finished, print DONE
#   $0 status   rows written per shard
set -u
SELF="$(readlink -f "$0")"
OUT=${shq(out)}
SHARDS=${opts.shards}
cd ${shq(cwd)} || exit 1
case "\${1:-start}" in
  start)
    mkdir -p "$OUT"
    rm -f "$OUT/DONE" "$OUT"/shard-*.jsonl "$OUT"/shard-*.log
    setsid nohup "$SELF" __coord > "$OUT/coord.log" 2>&1 < /dev/null &
    echo $! > "$OUT/coord.pid"
    echo "started $SHARDS shards -> $OUT (coordinator pid $(cat "$OUT/coord.pid")); wait with: $SELF wait"
    ;;
  __coord)
    pids=()
    for ((i = 0; i < SHARDS; i++)); do
      SHARD=$i SHARDS=$SHARDS OUT="$OUT" ${env ? env + " " : ""}nice -n ${nice} bash -c ${shq(opts.command)} \\
        > "$OUT/shard-$i.jsonl" 2> "$OUT/shard-$i.log" < /dev/null &
      pids+=($!)
    done
    codes=()
    for p in "\${pids[@]}"; do
      wait "$p"
      codes+=($?)
    done
    {
      echo "finished $(date -Is)"
      echo "codes \${codes[*]}"
    } > "$OUT/DONE.tmp"
    mv "$OUT/DONE.tmp" "$OUT/DONE"
    ;;
  wait)
    if [ ! -f "$OUT/DONE" ]; then
      pid="$(cat "$OUT/coord.pid" 2> /dev/null)"
      [ -n "$pid" ] && tail --pid="$pid" -f /dev/null
    fi
    cat "$OUT/DONE" 2> /dev/null || { echo "no DONE in $OUT (coordinator died? see $OUT/coord.log)"; exit 1; }
    grep -q "^codes \\(0 \\)*0$" "$OUT/DONE" || { echo "some shards failed: see $OUT/shard-*.log"; exit 1; }
    ;;
  status)
    wc -l "$OUT"/shard-*.jsonl
    [ -f "$OUT/DONE" ] && cat "$OUT/DONE"
    ;;
  *)
    echo "usage: $0 [start|wait|status]"
    exit 2
    ;;
esac
`;
}

/** Write the launcher to `path` (executable). */
export function writeLauncher(path: string, opts: LauncherOptions): string {
  mkdirSync(dirname(resolve(path)), { recursive: true });
  writeFileSync(path, launcherScript(opts));
  chmodSync(path, 0o755);
  return resolve(path);
}
